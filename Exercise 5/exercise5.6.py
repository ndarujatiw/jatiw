umur = 18

if umur < 2:
    print("Orang ini adalah bayi.")
elif umur < 4:
    print("Orang ini adalah balita.")
elif umur < 13:
    print("Orang ini adalah anak-anak.")
elif umur < 20:
    print("Orang ini adalah remaja.")
elif umur < 65:
    print("Orang ini adalah dewasa.")
else:
    print("Orang ini adalah lansia.")